import type { EvalReport } from './types'

/**
 * Renders the committed baseline report. Kept separate from the runner so the
 * document is a pure function of the report object: there is exactly one place
 * that decides how a number is displayed, and it cannot disagree with the JSON
 * written beside it.
 */

const format = (value: number): string => value.toFixed(4)

export function renderMarkdown(report: EvalReport): string {
  const { config, metrics, timing } = report
  const chunking = config.chunking

  // Built before the template because a nested template literal would terminate the
  // outer one; the map is a statement here, not an interpolation.
  const typeRows = report.byType
    .map(
      (entry) =>
        `| ${entry.type} | ${entry.questions} | ${format(entry.metrics.recallAt5)} | ` +
        `${format(entry.metrics.ndcgAt10)} | ${format(entry.metrics.hitRateAt5)} | ` +
        `${format(entry.metrics.mapAt10)} |`
    )
    .join('\n')

  return `# RAG eval baseline — ${report.baseline}

Generated by \`${report.generatedBy}\`. The numbers below are harness output — do not edit them by hand.

## Configuration

| Setting | Value |
| --- | --- |
| Embedding | \`${config.embedding}\` |
| Chunking | \`chunkSize=${chunking.chunkSize}, chunkOverlap=${chunking.chunkOverlap}, minChunkSize=${chunking.minChunkSize}, allowSpanPages=${chunking.allowSpanPages}, respectHeadings=${chunking.respectHeadings}\` |
| Retrieval | \`${config.retrieval}\` |
| Ranks | \`candidateK=${config.candidateK}, threshold=${config.threshold}\` |
| Context width | \`contextK=${config.contextK}\` |
| Corpus | \`${config.corpus}\` (${config.documents} documents) |
| Split | \`${config.split}\` (${config.questions} questions) |
| Index size | ${config.chunkCount} chunks |

## Metrics

| Metric | Value |
| --- | --- |
| Recall@1 | ${format(metrics.recallAt1)} |
| Recall@5 | ${format(metrics.recallAt5)} |
| Recall@10 | ${format(metrics.recallAt10)} |
| MRR | ${format(metrics.mrr)} |
| nDCG@10 | ${format(metrics.ndcgAt10)} |
| Hit rate@5 | ${format(metrics.hitRateAt5)} |
| MAP@10 | ${format(metrics.mapAt10)} |
| Context precision@${config.contextK} | ${format(metrics.contextPrecision)} |
| Context recall@${config.contextK} | ${format(metrics.contextRecall)} |

### By query type

A single average hides a change that helps one kind of question and hurts another.
The type comes from \`type\` in \`questions.jsonl\`; untagged questions report as
\`untagged\` rather than disappearing.

| Type | Questions | Recall@5 | nDCG@10 | Hit rate@5 | MAP@10 |
| --- | --- | --- | --- | --- | --- |
${typeRows}

Timing is informational only and is **not** frozen: indexing ${timing.indexingMs} ms, query
p50 ${timing.latencyP50Ms.toFixed(2)} ms, p95 ${timing.latencyP95Ms.toFixed(2)} ms on the
machine that produced this file. Timing and index size depend on hardware and on the
corpus, so they must never be the reason two runs differ.

## Definitions

- A retrieved passage is relevant when its provenance covers a ground-truth block.
- **Recall@k** is the share of ground-truth blocks covered by the first \`k\` passages.
- **Context precision@${config.contextK}** is the share of the first \`${config.contextK}\`
  retrieved passages that cover a ground-truth block. **Context recall@${config.contextK}** is
  the share of the needed ground-truth blocks that made it into that same window. Both are
  deterministic: the dataset says which blocks answer the question, so no model is needed to
  score the window. Together they are the trade-off a \`contextK\` decision actually makes —
  a wider window finds more and carries more noise.
- This is **retrieval precision/recall, not answer citation recall**: the harness runs no
  model and produces no answer. Answer-level citation correctness is covered by the
  resolver (#70). Faithfulness, completeness and answer correctness need a generative model
  and are **not evaluated here** — the harness runs offline with only the pinned embedding
  model, the same constraint that keeps the reranker unmeasured (#170).
- Ground truth is expressed in corpus identity (\`document\` relative path + \`block\`
  ordinal + optional \`quote\`), never a runtime \`documentId\`/\`blockId\`.

## Comparison protocol

Experiments (#77, #78) are reported as a **delta against this file**. From v1.6 on,
the harness runs the **production configuration** by default: \`candidateK\` is the
first-stage width per channel, \`contextK\` is how many passages the chat prompt takes,
and \`threshold\` is the similarity floor the app ships. A benchmark that does not
mirror those parameters measures a retriever nobody runs. The adopted-change rule is:

> Adopt a strategy when it improves the **first metric with headroom** — in the order
> Recall@5, nDCG@10, MRR, MAP@10 — and regresses none of the others. A metric already
> at its maximum has no headroom and cannot decide anything; a rule that depends on
> one is unsatisfiable, not strict (#192 child 10).
>
> A change that trades a large latency increase for a marginal quality gain is a
> product decision, not an automatic win, and must be stated as such.

A changed result must be reproducible with:

\`\`\`bash
npm run eval:prepare   # one-time, networked model bootstrap
npm run eval           # offline and deterministic
\`\`\`

The raw report is committed next to this summary as \`baseline-${report.baseline}.json\`.
`
}
